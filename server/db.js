function usesRemoteDatabase() {
  return Boolean(process.env.DATABASE_URL);
}

function toPostgresSql(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

function normalizeValue(value) {
  if (value instanceof Date) return value.toISOString();
  if (typeof value === 'bigint') return Number(value);
  return value;
}

function normalizeRows(rows = []) {
  return rows.map((row) => {
    const out = {};
    for (const [key, value] of Object.entries(row)) out[key] = normalizeValue(value);
    return out;
  });
}

function wrap(queryable) {
  return {
    async query(sql, params = []) {
      const result = await queryable.query(toPostgresSql(sql), params);
      return {
        rows: normalizeRows(result.rows || []),
        rowCount: result.rowCount ?? result.affectedRows ?? 0
      };
    },
    async all(sql, params = []) {
      return (await this.query(sql, params)).rows;
    },
    async get(sql, params = []) {
      return (await this.query(sql, params)).rows[0] || null;
    },
    async run(sql, params = []) {
      const result = await this.query(sql, params);
      return {
        ...result,
        lastInsertId: result.rows[0]?.id ?? null
      };
    }
  };
}

async function getLocalDb() {
  if (!localDb) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
    const { PGlite } = require('@electric-sql/pglite');
    localDb = new PGlite(LOCAL_DB_PATH);
  }
  return localDb;
}

async function getRemotePool() {
  if (!remotePool) {
    const { Pool } = require('@neondatabase/serverless');
    remotePool = new Pool({ connectionString: process.env.DATABASE_URL });
  }
  return remotePool;
}

async function baseQueryable() {
  if (usesRemoteDatabase()) return wrap(await getRemotePool());
  return wrap(await getLocalDb());
}

async function query(sql, params = []) {
  return (await baseQueryable()).query(sql, params);
}

async function all(sql, params = []) {
  return (await baseQueryable()).all(sql, params);
}

async function get(sql, params = []) {
  return (await baseQueryable()).get(sql, params);
}

async function run(sql, params = []) {
  return (await baseQueryable()).run(sql, params);
}

async function transaction(callback) {
  if (usesRemoteDatabase()) {
    const pool = await getRemotePool();
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await callback(wrap(client));
      await client.query('COMMIT');
      return result;
    } catch (error) {
      try {
        await client.query('ROLLBACK');
      } catch {}
      throw error;
    } finally {
      client.release();
    }
  }
  const database = await getLocalDb();
  return database.transaction(async (tx) => callback(wrap(tx)));
}

function makeVin(seq) {
  return `ANIIS${String(1000000000000 + seq).slice(1)}`;
}

function roundTo(value, step = 50) {
  return Math.round(value / step) * step;
}

function categoryPhrase(category) {
  const map = {
    Sedan: 'four-door saloon', SUV: 'commanding sport utility vehicle', Sports: 'low-slung performance car',
    Coupe: 'grand touring coupe', Pickup: 'capable pickup', Hatchback: 'agile hatchback', Van: 'versatile people mover',
    Convertible: 'open-top roadster', Wagon: 'long-roof tourer'
  };
  return map[category] || 'automobile';
}

function engineFor(fuel, price, category, brand) {
  if (fuel === 'Electric') {
    if (price > 450000) return 'Tri-Motor Electric Drive';
    if (price > 90000) return 'Dual-Motor Performance Electric';
    return 'Dual-Motor Electric Drive';
  }
  if (fuel === 'Hybrid') {
    if (price > 120000) return '4.0L Twin-Turbo Hybrid V8';
    if (price > 60000) return '3.0L Turbo Hybrid I6';
    return '2.5L Hybrid I4';
  }
  if (fuel === 'Diesel') return price > 60000 ? '3.0L Turbo Diesel V6' : '2.0L Turbo Diesel I4';
  const hyperEngines = {
    Bugatti: '8.0L Quad-Turbo W16',
    Ferrari: '3.9L Twin-Turbo V8',
    Lamborghini: '5.2L Naturally Aspirated V10',
    'Aston Martin': '4.0L Twin-Turbo V8',
    McLaren: '4.0L Twin-Turbo V8',
    'Rolls-Royce': '6.75L Twin-Turbo V12',
    Bentley: '4.0L Twin-Turbo V8',
    Porsche: '3.0L Twin-Turbo Flat-6'
  };
  if (price > 180000 && hyperEngines[brand]) return hyperEngines[brand];
  if (price > 120000) return '4.0L Twin-Turbo V8';
  if (price > 65000) return '3.0L Turbo I6';
  if (price > 38000) return '2.0L Turbo I4';
  if (category === 'Pickup') return '3.5L V6';
  return '2.0L I4';
}

function transmissionFor(model, fuel, price, category) {
  if (fuel === 'Electric') return 'Single-Speed';
  if (MANUAL_MODELS.has(model)) return '6-Speed Manual';
  if (category === 'Pickup') return '10-Speed Automatic';
  if (category === 'Sports' || category === 'Coupe' || category === 'Convertible') return price > 90000 ? '8-Speed DCT' : '8-Speed Automatic';
  if (price < 30000 && ['Sedan', 'Hatchback', 'SUV', 'Wagon'].includes(category)) return 'CVT Automatic';
  return price > 70000 ? '8-Speed Automatic' : '7-Speed DCT';
}

function drivetrainFor(seq, category, fuel, price, brand) {
  if (category === 'Pickup') return '4WD';
  if (category === 'Van') return 'FWD';
  if (category === 'Wagon') return 'AWD';
  if (fuel === 'Electric') return price > 150000 || seq % 3 !== 0 ? 'AWD' : 'RWD';
  if (category === 'Sports' || category === 'Coupe' || category === 'Convertible') {
    return ['Lamborghini', 'Bugatti', 'Audi'].includes(brand) ? 'AWD' : 'RWD';
  }
  if (category === 'SUV') return price > 52000 || seq % 2 === 0 ? 'AWD' : 'FWD';
  if (category === 'Hatchback') return price > 45000 && seq % 2 === 0 ? 'AWD' : 'FWD';
  if (price > 52000) return seq % 3 === 0 ? 'AWD' : 'RWD';
  return 'FWD';
}

function pickFeatures(seq, category, fuel, price) {
  const out = [];
  const add = (arr, count, offset = 0) => {
    for (let i = 0; i < count; i++) {
      const item = arr[(seq * 3 + offset + i * 5) % arr.length];
      if (!out.includes(item)) out.push(item);
    }
  };
  add(FEATURE_POOL.base, 4);
  if (fuel === 'Electric') add(FEATURE_POOL.ev, 3, 2);
  if (['SUV', 'Pickup'].includes(category)) add(FEATURE_POOL.offroad, 2, 1);
  if (['Sports', 'Coupe', 'Convertible'].includes(category)) add(FEATURE_POOL.performance, 3, 3);
  if (price > 50000) add(FEATURE_POOL.premium, 3, 4);
  if (price > 150000) add(FEATURE_POOL.premium, 3, 8);
  return out.slice(0, 12);
}

function pickSafety(seq, price) {
  const count = price > 100000 ? 8 : price > 50000 ? 6 : 4;
  const out = [];
  for (let i = 0; i < count; i++) {
    const item = SAFETY_POOL[(seq * 5 + i * 3) % SAFETY_POOL.length];
    if (!out.includes(item)) out.push(item);
  }
  return out;
}

function descriptionFor({ year, brand, model, variant, category, fuel, engine, horsepower, torque, color, condition }) {
  const phrase = categoryPhrase(category);
  if (condition === 'Certified Pre-Owned') {
    return `This certified pre-owned ${year} ${brand} ${model} ${variant} has been through a rigorous 172-point inspection and is offered with a comprehensive limited warranty. Its ${engine} delivers ${horsepower} hp and ${torque} lb-ft through a ${fuel.toLowerCase()} powertrain, while the specification and ${color.toLowerCase()} finish present beautifully. A rare opportunity to own a meticulously maintained ${phrase} at exceptional value.`;
  }
  return `The ${year} ${brand} ${model} ${variant} is a ${phrase} engineered to make every journey feel occasion-worthy. Under the bonnet, the ${engine} produces ${horsepower} hp and ${torque} lb-ft, paired with a responsive chassis and an effortlessly refined cabin. Finished in ${color} and available now from the AniissAuto collection, this ${fuel === 'Electric' ? 'zero-emission' : fuel === 'Hybrid' ? 'electrified' : 'highly specified'} example is ready for immediate delivery.`;
}

async function seedCatalog(tx) {
  const brandIds = new Map();
  for (const brand of catalog) {
    const result = await tx.run(
      'INSERT INTO brands (name, country, logo_color, tagline) VALUES (?, ?, ?, ?) RETURNING id',
      [brand.name, brand.country, brand.color, brand.tagline]
    );
    brandIds.set(brand.name, result.lastInsertId);
  }

  const rows = [];
  let seq = 0;
  for (const brand of catalog) {
    const brandId = brandIds.get(brand.name);
    brand.models.forEach((entry, modelIndex) => {
      const [model, category, basePrice] = entry;
      const fuel = entry[3] || 'Petrol';

      for (let listing = 0; listing < 2; listing++) {
        seq += 1;
        const variants = VARIANTS[category] || VARIANTS.Sedan;
        const variant = variants[(modelIndex + listing * 2) % variants.length];
        const trimPremium = listing === 0 ? 1 : 1.085;
        const rawPrice = basePrice * trimPremium + ((seq % 4) * 250);
        const isCpo = seq % 6 === 0;
        const condition = isCpo ? 'Certified Pre-Owned' : 'New';
        const year = isCpo ? 2022 + (seq % 3) : 2024 + (seq % 3);
        const mileage = isCpo ? 8500 + ((seq * 977) % 39000) : 0;
        const price = isCpo
          ? roundTo(rawPrice * (0.79 + (seq % 4) * 0.02))
          : roundTo(rawPrice);
        const msrp = isCpo
          ? roundTo(rawPrice)
          : roundTo(rawPrice * (1.025 + (seq % 3) * 0.015));
        const [colorName, colorHex] = COLORS[(seq * 7 + modelIndex) % COLORS.length];
        const stock = seq % 31 === 0 ? 0 : 1 + ((seq * 3) % 6);
        const featured = (seq < 14 || seq % 37 === 0) && stock > 0 ? 1 : 0;
        let badge = null;
        if (isCpo) badge = 'Certified';
        else if (seq % 41 === 0) badge = 'New Arrival';
        else if (seq % 53 === 0) badge = 'Best Seller';
        else if (fuel === 'Electric' && seq % 2 === 0) badge = 'Electric';
        else if (stock === 1) badge = 'Only 1 Left';
        else if (featured) badge = 'Featured';
        const engine = engineFor(fuel, price, category, brand.name);
        const hpBase = 140 + Math.sqrt(price) * 0.55;
        const horsepower = Math.round((hpBase * (['Sports', 'Coupe', 'Convertible'].includes(category) ? 1.12 : 1)) / 5) * 5;
        const torqueMultiplier = fuel === 'Electric' ? 1.55 : fuel === 'Diesel' ? 1.45 : fuel === 'Hybrid' ? 1.18 : 1.04;
        const torque = Math.round((horsepower * torqueMultiplier) / 10) * 10;
        const seats = category === 'Sports' ? 2 : category === 'Van' ? 7 : category === 'Coupe' || category === 'Convertible' ? 4 : category === 'SUV' && price > 70000 && seq % 2 === 0 ? 7 : 5;
        const doors = ['Sports', 'Coupe', 'Convertible'].includes(category) ? 2 : category === 'Van' ? 5 : 4;
        const transmission = transmissionFor(model, fuel, price, category);
        const drivetrain = drivetrainFor(seq, category, fuel, price, brand.name);
        const features = pickFeatures(seq, category, fuel, price);
        const safety = pickSafety(seq, price);
        const description = descriptionFor({
          year, brand: brand.name, model, variant, category, fuel, engine, horsepower, torque, color: colorName, condition
        });

        rows.push([
          brandId, model, variant, year, category, price, msrp, condition, mileage, fuel,
          transmission, drivetrain, engine, horsepower, torque, seats, doors, colorName,
          colorHex, stock, makeVin(seq), featured, badge, description,
          JSON.stringify(features), JSON.stringify(safety), 0, 0
        ]);
      }
    });
  }

  const columns = VEHICLE_COLUMNS.join(', ');
  for (let start = 0; start < rows.length; start += 40) {
    const chunk = rows.slice(start, start + 40);
    const params = [];
    const values = chunk.map((row) => {
      const placeholders = row.map((value) => {
        params.push(value);
        return `$${params.length}`;
      });
      return `(${placeholders.join(', ')})`;
    });
    await tx.query(`INSERT INTO vehicles (${columns}) VALUES ${values.join(', ')}`, params);
  }
  return rows.length;
}

async function ensureAdmin(tx) {
  const existing = await tx.get(
    'SELECT id FROM users WHERE lower(username) = lower(?) OR lower(email) = lower(?)',
    [ADMIN.username, ADMIN.email]
  );
  if (existing) return;
  const { salt, hash } = hashPassword(ADMIN.password);
  await tx.run(
    `INSERT INTO users (username, name, email, password_hash, password_salt, role)
     VALUES (?, ?, ?, ?, ?, 'admin') ON CONFLICT DO NOTHING`,
    [ADMIN.username, ADMIN.name, ADMIN.email, hash, salt]
  );
}

async function ensureSettings(tx) {
  for (const [key, value] of Object.entries(DEFAULT_SETTINGS)) {
    await tx.run(
      'INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO NOTHING',
      [key, value]
    );
  }
}

async function initDb() {
  if (dbInfo) return dbInfo;
  if (initPromise) return initPromise;
  initPromise = (async () => {
    const database = await baseQueryable();
    for (const statement of SCHEMA) await database.query(statement);
    await ensureSettings(database);
    await ensureAdmin(database);
    let vehicles = 0;
    await transaction(async (tx) => {
      if (usesRemoteDatabase()) await tx.query('SELECT pg_advisory_xact_lock(948623071)');
      const countRow = await tx.get('SELECT COUNT(*)::int AS count FROM brands');
      if (!countRow.count) {
        vehicles = await seedCatalog(tx);
        console.log(`[AniissAuto] Seeded ${vehicles} vehicles across ${catalog.length} brands.`);
      }
    });
    dbInfo = usesRemoteDatabase()
      ? { mode: 'neon', label: `Neon Postgres (${new URL(process.env.DATABASE_URL).host})` }
      : { mode: 'local', label: LOCAL_DB_PATH };
    console.log(`[AniissAuto] Database ready: ${dbInfo.label}`);
    return dbInfo;
  })().catch((error) => {
    initPromise = undefined;
    throw error;
  });
  return initPromise;
}

async function closeDb() {
  if (remotePool) {
    await remotePool.end();
    remotePool = undefined;
  }
  if (localDb) {
    await localDb.close();
    localDb = undefined;
  }
  initPromise = undefined;
  dbInfo = undefined;
}

